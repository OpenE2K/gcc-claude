#!/usr/bin/env python3
# Generate e2k-builtins.def, lcc's operation builtins, from the relcc2
# specification's data (spec/abi/lcc-builtins*.yaml, spec/isa).
# Written by Claude (Anthropic) as an experiment; see README.claude.
#
# This file is part of GCC.
#
# GCC is free software; you can redistribute it and/or modify it under
# the terms of the GNU General Public License as published by the Free
# Software Foundation; either version 3, or (at your option) any later
# version.
#
#   gen-e2k-builtins.py RELCC2-DIR > e2k-builtins.def
#   gen-e2k-builtins.py --header RELCC2-DIR > e2kintrin-ops.h
#
# The header has lcc's short forms, _e2k_<op> for __builtin_e2k_<op>,
# those of v6 and v7 operations only from their version, as lcc's
# <e2kintrin.h> has them (relcc2 spec/abi/lcc-builtins.md).
#
# Each builtin is the operations lcc 1.31.05 compiles it to
# (lcc-builtins-check.yaml), written as lcc's own trace: "pextrh a0, a1,
# {k2&0xff}, ret" is the operation pextrh with the C arguments 0 and 1
# as its first two operands, argument 2, a constant masked to 8 bits, as
# its literal and the result as its destination; "plog_{k0&0xff:02x}" a
# mnemonic whose suffix is a constant argument.  The kind says how a
# builtin that isn't one operation on its arguments is built
# (e2k-builtins.cc).  The type is the port's insn type (e2k.md) whose
# channels are the operation's on every ISA version it exists on
# (binutils-ops.yaml) and whose latency is nearest the measured one
# (timing-e2s.yaml, -e8c2, -e2c3).

import re
import sys
import yaml

KINDS_BY_NAME = {
    # Memory with a MAS, speculative loads, prefetch (e2k-builtins.cc).
    "ld_64s_cleartag": "LD_CLEARTAG", "ld_128_cleartag": "LD_CLEARTAG",
    "ld_64s_sm": "LD_SM", "ld_128_sm": "LD_SM",
    "st_64s_nt": "ST", "st_128_nt": "ST", "st_32u_nt": "ST",
    "pst_128": "PST",
}

# The port's types (e2k.md "type"): channels as e2k_chan_set gives them
# (a function of the ISA version for the FP ones) and latency.
TYPES = {
    "ALU": (lambda v: 0x3f, 1), "ALU14": (lambda v: 0x12, 1),
    "ALU0134": (lambda v: 0x1b, 1), "MUL": (lambda v: 0x1b, 4),
    "DIV": (lambda v: 0x20, 15), "FDIV": (lambda v: 0x20, 14),
    "FP": (lambda v: 0x3f if v >= 4 else 0x1b, 4),
    "FMA": (lambda v: 0x3f if v >= 4 else 0x1b, 8),
    "FFMA": (lambda v: 0x3f if v >= 4 else 0x1b, 5),
    "FCVT": (lambda v: 0x1b, 4), "FSCALE": (lambda v: 0x12, 4),
    "FLAG": (lambda v: 0x09, 4), "FLAGMUL": (lambda v: 0x09, 6),
    "ALU25": (lambda v: 0x24, 1),
    "PINT": (lambda v: 0x09, 1), "PINT14": (lambda v: 0x12, 1),
    "PMUL": (lambda v: 0x12, 2), "PANY": (lambda v: 0x1b, 1),
}
# Types a packed, FP or integer operation may take.
PACKED = ["PINT", "PINT14", "PMUL", "PANY"]
FPT = ["FP", "FMA", "FFMA", "FCVT", "FSCALE", "FDIV"]
INT = ["ALU", "ALU14", "ALU0134", "MUL", "DIV", "FLAG", "FLAGMUL", "ALU25"]

TYPECODES = {
    "uint64": "U64", "uint32": "U32", "unsigned": "U32", "long": "I64",
    "v2di": "V2DI", "long double": "XF", "void*": "PTR",
    "const void*": "CPTR", "v2di*": "PTR", "const v2di*": "CPTR",
    "__e2k_hint": "U32", "N": "U32", "void": "VOID",
}


def load(path):
    with open(path) as f:
        return yaml.safe_load(f)


HEADER_HEAD = """/* Generated by gen-e2k-builtins.py from the relcc2 specification: lcc's
   short forms of its operation builtins.  Do not edit.  Included by
   <e2kintrin.h>.

   This file is part of GCC.

   GCC is free software; you can redistribute it and/or modify it under
   the terms of the GNU General Public License as published by the Free
   Software Foundation; either version 3, or (at your option) any later
   version.

   Under Section 7 of GPL version 3, you are granted additional
   permissions described in the GCC Runtime Library Exception, version
   3.1, as published by the Free Software Foundation.  */

#ifndef _E2KINTRIN_H
#error "Include <e2kintrin.h> instead of <e2kintrin-ops.h>."
#endif
"""


def main():
    header = sys.argv[1] == "--header"
    if header:
        del sys.argv[1]
    root = sys.argv[1]
    spec = f"{root}/spec"
    names = {b["name"]: b for b in load(f"{spec}/abi/lcc-builtins.yaml")["builtins"]}
    check = load(f"{spec}/abi/lcc-builtins-check.yaml")["builtins"]
    ops = load(f"{spec}/isa/binutils-ops.yaml")
    chans, alopf = {}, {}
    for lst in ops.values():
        if not isinstance(lst, list):
            continue
        for e in lst:
            if not isinstance(e, dict) or "name" not in e:
                continue
            for n in [e["name"]] + list(e.get("aliases") or []):
                alopf.setdefault(n, e.get("alopf"))
                for v in e.get("isets", []):
                    m = sum(1 << c for c in e.get("channels", []))
                    chans.setdefault(n, {})[v] = chans.get(n, {}).get(v, 0) | m
    lat = {}
    for f, v in (("timing-e2s", 3), ("timing-e8c2", 5), ("timing-e2c3", 6)):
        sl = load(f"{spec}/isa/{f}.yaml").get("scheduled_latency", {})
        for k, d in sl.items():
            if isinstance(d, dict) and "latency" in d:
                m = re.fullmatch(r"(?:v\dop_)?([a-z0-9_]+)", k)
                if m and not k.endswith(("_to_addd", "_x")):
                    lat.setdefault(m.group(1), {})[v] = d["latency"]

    out, skipped = [], []
    for name, b in names.items():
        if b.get("group") != "op":
            continue
        c = check.get(name)
        if not c:
            skipped.append((name, "no check data"))
            continue
        short = name[len("__builtin_e2k_"):]
        iset = c.get("iset", b.get("iset", 1))
        sig = c.get("lcc_signature", {})
        ret = sig.get("returns", b["returns"])
        args = sig.get("args", [a["type"] for a in b["args"]])
        if "|" in ret:
            ret = ret.split("|")[0].strip()
        asm = c.get("asm", [])
        consts = c.get("constant_args", {}) or {}
        kind, tmpl, mn = classify(short, asm, consts)
        if kind is None:
            skipped.append((name, tmpl))
            continue
        ty = (choose_type(mn, iset, chans, lat, PACKED if kind == "PRED" else None)
              if mn else "ALU")
        # A constant in an 8-bit ALES field (or a v7 _lt3 form's encoded
        # one) takes no literal syllable and no register.
        if mn and alopf.get(mn) in ("ALOPF11_LIT8", "ALOPF21_LT_PACK_CODE"):
            tmpl = re.sub(r"\{(k\d[^}:]*)\}", r"{\1!}", tmpl)
        if ty is None:
            skipped.append((name, f"no type for {mn}: channels "
                            f"{ {v: hex(m) for v, m in chans.get(mn, {}).items()} }"))
            continue
        try:
            codes = [TYPECODES[ret]] + [TYPECODES[a] for a in args]
        except KeyError as e:
            skipped.append((name, f"type {e}"))
            continue
        codes += ["NONE"] * (5 - len(codes))
        out.append(f'E2K_BUILTIN ("{short}", {kind}, {iset}, {ty}, "{tmpl}", '
                   + ", ".join(codes) + ")")

    if header:
        hdr = load(f"{spec}/abi/lcc-builtins-names.yaml")["header"]
        print(HEADER_HEAD)
        guard = None
        for n in sorted(hdr, key=lambda n: (min(hdr[n].get("isets", [3])), n)):
            if not n.startswith("_e2k_"):
                continue
            v = min(hdr[n].get("isets", [3]))
            g = v if v >= 6 else None
            if g != guard:
                if guard:
                    print("#endif")
                if g:
                    print(f"#if __iset__ >= {g}")
                guard = g
            print(f"#define {n} __builtin_e2k_{n[5:]}")
        if guard:
            print("#endif")
        return
    print("/* Generated by gen-e2k-builtins.py from the relcc2 specification:")
    print("   lcc's operation builtins.  Do not edit.  */")
    print()
    for line in out:
        print(line)
    print()
    print(f"/* {len(out)} builtins; not generated ({len(skipped)}):")
    for n, why in skipped:
        print(f"   {n}: {why}".replace("*/", "* /"))
    print("*/")


def classify(short, asm, consts):
    """Kind, template and the main mnemonic of a builtin, or None and why."""
    if short in KINDS_BY_NAME:
        return KINDS_BY_NAME[short], " | ".join(asm), None
    if short == "pshufh":
        return "SHUFH", "pshufb 0x0, a0, {k1}, ret", "pshufb"
    if short == "qppackdl":
        return "PACK", "", None
    if short == "qpswitchd":
        # lcc swaps the halves by itself; qpswitchd is the operation.
        return "RULE", "qpswitchd a0, ret", "qpswitchd"
    if any(a.startswith("asm:") for a in asm):
        return None, "inline asm in lcc's code", None
    if len(asm) == 2 and re.fullmatch(r"merged,sm 0x0, 0x1, ret, t1", asm[1]) \
            and asm[0].endswith(", t1"):
        t = asm[0][: -len(", t1")]
        return "PRED", subst(t, consts), mnemonic(t)
    if len(asm) == 2 and asm[0] == "movif a0.lo, a0.hi, t1" \
            and asm[1].startswith(("fx", "fsx")) and asm[1].endswith(", ret"):
        t = asm[1].replace("t1", "a0")
        return "FX", subst(t, consts), mnemonic(t)
    if len(asm) == 2 and re.fullmatch(r"qppackdl 0x[0-9a-f]+, 0x[0-9a-f]+, t1", asm[0]) \
            and asm[1].endswith(", t1, ret"):
        hi, lo = re.findall(r"0x[0-9a-f]+", asm[0])
        t = asm[1].replace("t1", "{q" + lo + ":" + hi + "}")
        return "RULE", t, mnemonic(asm[1])
    if len(asm) != 1:
        return None, f"{len(asm)} operations", None
    a = asm[0]
    if "mas=" in a or a.split()[0].startswith(("ld", "st")):
        return None, "memory access", None
    if re.search(r"\bt\d\b|\.lo|\.hi|%", a):
        return None, f"shape {a}", None
    return "RULE", subst(a, consts), mnemonic(a)


def mnemonic(t):
    return re.sub(r"_\{k\d.*", "", t.split()[0].split(",")[0])


def subst(t, consts):
    """Replace the literals lcc printed for constant arguments by
    placeholders, with the mask its emitted values show."""
    for i, info in sorted(consts.items()):
        p = info.get("probed_with")
        emitted = info.get("emitted", {}) or {}
        mask = None
        for m in (0x1, 0x3, 0x7, 0xf, 0x1f, 0x3f, 0x7f, 0xff, 0xffff):
            if emitted and all(re.search(r"\b%s\b" % re.escape(hex(v & m)), s)
                               or re.search(r"_%s" % re.escape("0x%02x" % (v & m)), s)
                               for v, s in emitted.items()):
                mask = m
                break
        mk = f"&{hex(mask)}" if mask else ""
        suffix = "_0x%02x" % p
        head, _, rest = t.partition(" ")
        if suffix in head:
            head = head.replace(suffix, "_{k%d%s:02x}" % (i, mk), 1)
            t = head + " " + rest
        else:
            rest = re.sub(r"\b%s\b" % re.escape(hex(p)), "{k%d%s}" % (i, mk),
                          rest, count=1)
            t = head + " " + rest
    return t


def choose_type(mn, iset, chans, lat, only=None):
    """The port's type for operation MN in builtins of ISET and later
    (among ONLY if given)."""
    ch = chans.get(mn)
    if not ch:
        return None
    vs = [v for v in range(max(iset, 3), 7) if v in ch]
    if not vs:
        vs = [v for v in sorted(ch) if v >= max(iset, 3)][:1]
    if not vs:
        return None
    if mn.startswith(("p", "qp")) and not mn.startswith(("pf", "qpf")):
        cands = PACKED + INT
    elif mn.startswith(("f", "pf", "qpf")):
        cands = FPT + PACKED + INT
    else:
        cands = INT + FPT + PACKED
    if only:
        cands = only
    want = None
    for v in (3, 5, 6):
        if v in lat.get(mn, {}):
            want = lat[mn][v]
            break
    best = None
    for t in cands:
        f, l = TYPES[t]
        if all(f(v) == ch[v] for v in vs):
            d = abs(l - want) if want is not None else 0
            if best is None or d < best[0]:
                best = (d, t)
    return best and best[1]


if __name__ == "__main__":
    main()
